create table if not exists public.users_data (
  user_id uuid primary key references auth.users(id) on delete cascade,
  public_user_id text,
  email text not null,
  username text,
  first_name text,
  last_name text,
  gender text check (gender in ('male', 'female')),
  governorate text,
  age integer,
  weight numeric,
  height numeric,
  goal text default 'maintenance',
  completed_workouts integer not null default 0,
  goals_completed integer not null default 0,
  subscription_plan text check (subscription_plan in ('monthly', 'yearly', 'lifetime')),
  subscription_status text not null default 'trial' check (subscription_status in ('trial', 'active', 'expired', 'pending')),
  subscription_expires_at timestamptz,
  account_status text not null default 'active',
  suspended_until timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

